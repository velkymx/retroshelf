'use strict';

const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawn, spawnSync } = require('child_process');
const { generateDosboxConfig } = require('./dosboxConfig');
const { buildRawLaunch } = require('./scanner');

function exists(p) {
  try {
    return Boolean(p) && fs.existsSync(p);
  } catch {
    return false;
  }
}

function which(cmd) {
  const res = spawnSync(process.platform === 'win32' ? 'where' : 'which', [cmd], { encoding: 'utf8' });
  if (res.status !== 0) return null;
  const first = res.stdout.split(/\r?\n/).find(Boolean);
  return first || null;
}

/** DOSBox Staging keeps its config dir (soundfonts, MT-32 ROMs) in a per-OS location. */
function dosboxConfigDir() {
  const home = os.homedir();
  if (process.platform === 'darwin') return path.join(home, 'Library', 'Preferences', 'DOSBox');
  if (process.platform === 'win32') return path.join(process.env.LOCALAPPDATA || path.join(home, 'AppData', 'Local'), 'DOSBox');
  return path.join(process.env.XDG_CONFIG_HOME || path.join(home, '.config'), 'dosbox');
}

function detectDosbox() {
  const home = os.homedir();
  const candidates = {
    darwin: ['/Applications/DOSBox Staging.app/Contents/MacOS/dosbox', path.join(home, 'Applications/DOSBox Staging.app/Contents/MacOS/dosbox')],
    win32: [
      path.join(process.env.ProgramFiles || 'C:\\Program Files', 'DOSBox Staging', 'dosbox.exe'),
      path.join(process.env.LOCALAPPDATA || '', 'Programs', 'DOSBox Staging', 'dosbox.exe'),
    ],
    linux: ['/usr/bin/dosbox', '/usr/local/bin/dosbox', path.join(home, '.local/bin/dosbox')],
  }[process.platform] || [];
  return candidates.find(exists) || which('dosbox') || null;
}

function detectScummvm() {
  const home = os.homedir();
  const candidates = {
    darwin: ['/Applications/ScummVM.app/Contents/MacOS/scummvm', path.join(home, 'Applications/ScummVM.app/Contents/MacOS/scummvm')],
    win32: [
      path.join(process.env.ProgramFiles || 'C:\\Program Files', 'ScummVM', 'scummvm.exe'),
      path.join(process.env['ProgramFiles(x86)'] || 'C:\\Program Files (x86)', 'ScummVM', 'scummvm.exe'),
    ],
    linux: ['/usr/bin/scummvm', '/usr/local/bin/scummvm', '/usr/games/scummvm'],
  }[process.platform] || [];
  return candidates.find(exists) || which('scummvm') || null;
}

function detectSoundfont() {
  const dir = path.join(dosboxConfigDir(), 'soundfonts');
  try {
    const sf = fs.readdirSync(dir).find((f) => /\.sf[23]$/i.test(f));
    return sf ? path.join(dir, sf) : null;
  } catch {
    return null;
  }
}

function detectMt32Roms() {
  const dir = path.join(dosboxConfigDir(), 'mt32-roms');
  try {
    return fs.readdirSync(dir).some((f) => /\.rom$/i.test(f)) ? dir : null;
  } catch {
    return null;
  }
}

/** Effective tool paths: user settings win, auto-detection fills the gaps. */
function resolveTools(settings) {
  return {
    dosbox: settings.dosboxPath || detectDosbox(),
    scummvm: settings.scummvmPath || detectScummvm(),
    soundfont: settings.soundfont || detectSoundfont(),
    mt32RomDir: settings.mt32RomDir || detectMt32Roms(),
  };
}

/** The DOS launch after applying the user's executable / startup-command overrides. */
function effectiveDosLaunch(game, libraryRoot) {
  let launch = game.launch.dos;
  if (game.source === 'raw' && game.exeOverride && game.exeOverride !== game.exe) {
    launch = buildRawLaunch({ dir: game.folder, root: libraryRoot, exe: game.exeOverride, cdImages: game.cdImages });
  }
  if (Array.isArray(game.commandsOverride) && game.commandsOverride.length) {
    launch = { ...launch, commands: game.commandsOverride };
  }
  return launch;
}

function buildDosboxConfig(game, settings, paths) {
  const tools = resolveTools(settings);
  const captureDir = path.join(paths.captures, game.id);
  const launchGame = { ...game, launch: { dos: effectiveDosLaunch(game, game.libraryRoot) } };
  return generateDosboxConfig(launchGame, settings, {
    platform: process.platform,
    soundfont: tools.soundfont,
    mt32RomDir: tools.mt32RomDir,
    captureDir,
  });
}

function buildScummvmIni(game, settings, paths) {
  const tools = resolveTools(settings);
  const s = game.launch.scummvm;
  const target = s.target || 'game';
  const o = game.overrides || {};
  const fullscreen = o.fullscreen !== undefined ? o.fullscreen : settings.fullscreen !== false;
  const pixelPerfect = (o.integerScaling || settings.integerScaling) === 'vertical';
  const lines = [
    `# Generated by RetroShelf for "${game.title}"`,
    '[scummvm]',
    `fullscreen=${fullscreen}`,
    'gfx_mode=opengl',
    `stretch_mode=${pixelPerfect ? 'pixel-perfect' : 'fit'}`,
    'aspect_ratio=true',
    `filtering=${settings.scummvmFiltering ? 'true' : 'false'}`,
    'subtitles=true',
    'speech_mute=false',
    'music_driver=auto',
    'multi_midi=true',
    'enable_gs=false',
    'confirm_exit=false',
    'updates_check=0',
    'gui_return_to_launcher_at_exit=false',
  ];
  if (tools.soundfont) lines.push(`soundfont=${tools.soundfont}`);
  lines.push('', `[${target}]`);
  if (s.gameId) lines.push(`gameid=${s.gameId}`, 'engineid=scumm');
  lines.push(`path=${s.dataPath}`, `description=${game.title}`, `savepath=${path.join(paths.saves, game.id)}`, '');
  return lines.join('\n');
}

/** Preview of whatever config the game would launch with. */
function previewConfig(game, settings, paths) {
  return game.engine === 'scummvm' ? buildScummvmIni(game, settings, paths) : buildDosboxConfig(game, settings, paths);
}

/**
 * Launch a game. Resolves to { child, configPath } once the process has spawned.
 */
function launchGame(game, settings, paths) {
  const tools = resolveTools(settings);
  fs.mkdirSync(paths.configs, { recursive: true });
  let exe;
  let args;
  let configPath;
  if (game.engine === 'scummvm') {
    if (!tools.scummvm) throw new Error('ScummVM was not found. Install it (scummvm.org) or set its path in Settings.');
    fs.mkdirSync(path.join(paths.saves, game.id), { recursive: true });
    configPath = path.join(paths.configs, `${game.id}.scummvm.ini`);
    fs.writeFileSync(configPath, buildScummvmIni(game, settings, paths));
    exe = tools.scummvm;
    const s = game.launch.scummvm;
    args = s.target ? [`--config=${configPath}`, s.target] : [`--config=${configPath}`, `--path=${s.dataPath}`, '--auto-detect'];
  } else {
    if (!tools.dosbox) throw new Error('DOSBox Staging was not found. Install it (dosbox-staging.github.io) or set its path in Settings.');
    fs.mkdirSync(path.join(paths.captures, game.id), { recursive: true });
    configPath = path.join(paths.configs, `${game.id}.conf`);
    fs.writeFileSync(configPath, buildDosboxConfig(game, settings, paths));
    exe = tools.dosbox;
    args = ['--nolocalconf'];
    if (settings.ignorePrimaryConf) args.push('--noprimaryconf');
    args.push('-conf', configPath);
  }
  return new Promise((resolve, reject) => {
    const child = spawn(exe, args, { cwd: game.folder, stdio: 'ignore' });
    child.once('error', reject);
    child.once('spawn', () => resolve({ child, configPath }));
  });
}

module.exports = {
  resolveTools,
  detectDosbox,
  detectScummvm,
  effectiveDosLaunch,
  previewConfig,
  launchGame,
  buildScummvmIni,
  dosboxConfigDir,
};
